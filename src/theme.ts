/**
 * 八大内容类别的固定配色。
 *
 * 这 8 个颜色经过「色盲安全」计算验证（相邻色差值均达标），顺序也是验证过的，
 * 不要随意调换顺序、也不要自己再加第 9 个颜色。
 *
 * 什么时候用：当多个类别作为「并列的系列」同时出现在一张图里时，按类别取色。
 * 什么时候不用：如果一张图只画一个指标（比如只画播放量），
 *   所有柱子用同一个颜色（SERIES_PRIMARY）就好——
 *   柱子长短已经把大小说清楚了，再涂成 8 种颜色是浪费，反而让人分心。
 */
export const CATEGORY_COLORS = [
  '#2a78d6', // 槽位 1 - 游戏
  '#eb6834', // 槽位 2 - 知识
  '#1baf7a', // 槽位 3 - 科技
  '#eda100', // 槽位 4 - 生活
  '#e87ba4', // 槽位 5 - 娱乐
  '#008300', // 槽位 6 - 动画
  '#4a3aa7', // 槽位 7 - 影视
  '#e34948', // 槽位 8 - 音乐
] as const

/** 单一数据系列的默认用色（槽位 1 的蓝）。 */
export const SERIES_PRIMARY = CATEGORY_COLORS[0]

/**
 * 有序色阶（浅 → 深）。
 * 用于「本身就有先后顺序」的分类，比如年龄段、漏斗层级。
 * 深浅代表的是"顺序位置"，不代表数值大小——数值大小仍然由柱子长度表达。
 * 注意：最浅的一档不能再浅了，否则在白底上看不清。
 */
export const ORDINAL_RAMP = [
  '#86b6ef',
  '#5598e7',
  '#2a78d6',
  '#1c5cab',
  '#104281',
  '#0d366b',
] as const

/**
 * 年龄段的固定配色（4 档，浅 → 深）。
 *
 * 从上面的有序色阶里挑了 4 档间隔均匀的，好处是：
 * 同一个年龄段在「用户规模图」「活跃率图」「明细表」里永远是同一个颜色，
 * 眼睛可以跨图对照，不用重新认一遍颜色。
 *
 * 顺序 = AGE_GROUP_IDS 的顺序：18–24 / 25–31 / 32–40 / 40+
 */
export const AGE_RAMP = [
  '#86b6ef',
  '#2a78d6',
  '#1c5cab',
  '#0d366b',
] as const

/** 按年龄段下标（0-3）取色 */
export function ageColor(index: number): string {
  return AGE_RAMP[index] ?? AGE_RAMP[AGE_RAMP.length - 1]
}

/** 图表内部的中性色：网格线、坐标轴、刻度文字。都刻意做得很淡，不跟数据抢戏。 */
export const CHART_INK = {
  grid: '#eef1f4',
  axis: '#cbd5e1',
  label: '#94a3b8',
  /** 轴上的刻度文字 */
  tick: '#94a3b8',
  /** 直接标注在图形上的数值文字，要能看清，所以比刻度深一档 */
  value: '#475569',
} as const

/** 涨跌状态色。只在表达"好/坏"时使用，不能拿去当普通系列色。 */
export const STATUS_COLOR = {
  up: '#0ca30c',
  down: '#d03b3b',
} as const

/** 按类别槽位（1-8）取色 */
export function categoryColor(slot: number): string {
  return CATEGORY_COLORS[(slot - 1) % CATEGORY_COLORS.length]
}
