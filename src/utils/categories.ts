/* ==========================================================================
   内容分区的唯一权威定义
   --------------------------------------------------------------------------
   和年龄段一样：全站所有涉及内容分区的地方都从这里取。
   顺序固定不变——顺序即配色槽位，槽位决定颜色。
   （配色在 src/theme.ts，第 1 个颜色给第 1 个类别，以此类推）
   ========================================================================== */

import type { CategoryName } from '../types'

export const CATEGORIES: CategoryName[] = [
  '游戏',
  '知识',
  '科技',
  '生活',
  '娱乐',
  '动画',
  '影视',
  '音乐',
]

/** 取分区的配色槽位（1-8） */
export function categorySlot(category: CategoryName): number {
  const idx = CATEGORIES.indexOf(category)
  return idx < 0 ? 1 : idx + 1
}
