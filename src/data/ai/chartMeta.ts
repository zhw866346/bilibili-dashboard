/* ==========================================================================
   图表卡片的文案查表
   --------------------------------------------------------------------------
   第 5 步「得到分析结果」要把每张图包进一张卡片：标题、副标题、单位、一句话提示。

   ★ 为什么单独成表，不写在 AgentWorkflow.tsx 里：
     原来是 `id === 'dauTrend' ? '…' : '…'` 这种二选一的三目写法。
     加第二类问题、多出两张图之后，它就会变成四选一的三目套三目 ——
     而且【漏掉一个分支不会报错】，只会让两张新图顶着第一张图的标题显示。

     写成 Record<ChartId, …> 之后，ChartId 上加一个成员而这里不补，
     是【编译错误】。这是本次改动里唯一一处「用类型把错误拦在编译期」的地方。

   ★ 文案里可以引用 plan（问的是哪一档人、窗口多少天），但【不许】引用结果数据 ——
     这个文件在结果出来之前就要能用，一旦依赖数据，图表还没画出来卡片就得先崩。
   ========================================================================== */

