export interface ChartMeta {
  title: string
  subtitle: string
  /** 卡片右上角那句小字，通常是单位 */
  meta: string
  note: string
  /**
   * 这张图的数据从哪儿来。
   *
   * ★ 它决定「画不出来时该怎么解释」：
   *   读离线 Pandas 的图（dauTrend / weightVsActual）在数据库起不来时**照样画得出来**，
   *   读 SQL 结果的图则画不出来。合成一句「加载失败」就是在含糊。
   *
   * ★ 三个成员而不是两个：大模型路径挑中的那一条结果
   *   很可能来自【本机 Python】（`pickChartable` 会优先挑变化率那一列，
   *   而 `change_pct` 恰恰是 Python 算出来的）。给它填 'sql' 就是一句假话。
   *
   * ⚠️ 如实说一件事：**这个字段现在【一个消费者都没有】**（src/ 里只有声明和 8 处赋值）。
   *    所以填错了不会有任何东西报错、也不会有任何脚本变红 ——
   *    「填对」目前只靠纪律，不靠构造。写在这里，免得下一个人以为它是被验过的。
   */
  source: 'sql' | 'offline' | 'llm-call'
  /**
   * 拿不到结果时，卡片正文里要显示的那句话（只写「缺了什么」，原因由 ChartBoard 按实际情况追加）。
   *
   * ★ 为什么设成必填：漏写一个分支【不会报错】，只会让那张图在出问题时
   *   静静地空着 —— 这正是这一页最不该有的失败形状。设成必填之后，漏了是编译错误。
   */
  emptyHint: string
}

