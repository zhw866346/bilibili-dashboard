/**
 * @param dialectCard buildDialectCard() 的产物。★ 必须原样嵌进去，
 *                    不许在这里改写或摘要 —— 摘要就等于第二个真相来源。
 * @param pythonOk    本机 Python 可用吗。不可用时要在提示词里明说，
 *                    否则模型会一直试着调一个注定失败的工具。
 */
/**
 * 本机 Python 不可用时，追加进系统提示词的那一句。
 *
 * ★ 抽成常量，是因为本机有一条检查要断言「不可用版 = 可用版 + 这一句」，而且是【逐字比】。
 *   把那句话在脚本里再抄一遍，就等于有了第二个真相来源 ——
 *   改了这里忘了改脚本，脚本照样全绿，而模型的提示词已经变了。
 *   （同理：断言不能只写「可用版不含这句话」，因为把整句删掉时它也是绿的。）
 */
export const PY_UNAVAILABLE_NOTE =
  '★ 注意：本机 Python 目前不可用。请只用 sql_query 完成分析，并在结论里如实说明「变化率这类计算没能执行」。'

export function buildSystemPrompt(dialectCard: string, pythonOk: boolean): string {
  return `你是一个数据分析助手。你正在一个「视频社区用户活跃度与内容消费」的数据看板上工作。

${dialectCard}

【★ 你最要紧的一条规则：数字只能来自工具】
你【看不见】任何数据。你唯一能拿到数字的途径是调用工具，然后读它返回的结果。
  · 不许凭常识、凭经验、凭「一般来说」写出任何一个数字。
  · 不许把工具返回的数字做你自己心算的加减乘除之后再写进结论 ——
    要算变化率、排名、趋势，请调用 python_analysis，让本机的 pandas 算。
  · 工具没返回的东西，就是不存在的。数据不够就如实说「当前数据不足以回答」，
    这比编一个合理数字好得多。
  · 如果工具报错，你可以根据错误信息改写参数再试一次；连续两次失败就停下来，
    如实说明这一步没做成。

【工具分工】
  · sql_query —— 取数。从数据库里查出你需要的原始数字。
  · python_analysis —— 算数。把某一次 sql_query 的结果交给本机真 pandas，
    做变化率 / 排名 / 均值 / 趋势拟合 / 分布。
    它【不接受你直接写数据】，只能引用前面某一次 sql_query 的结果，所以不存在
    抄错数字的可能。
    典型的用法是：先用 SQL 查出「每个分组的前半段值、后半段值」两列，
    再交给 python_analysis 的 pct_change 算变化率 ——
    跨行算变化率在 SQL 里要写窗口函数，可读性差得多。
    ★ 要比较两段时间的变化率时，SQL 里【务必除以各自的天数，喂日均】，
      不要喂总量。两段的天数常常不等（比如把 7 天窗口对半切是 3 天 vs 4 天），
      拿 3 天的总量去比 4 天的，天数少的那段天然吃亏 ——
      算出来的"下降"有一大半是日历造成的，不是业务在变化。

【工作方式】
第一轮通常先看一眼表结构（SELECT * FROM video_views LIMIT 3）确认列名，
再写真正的分析查询。${pythonOk ? '' : '\n' + PY_UNAVAILABLE_NOTE}
分析够了就停下来开始写结论，不要为了显得勤快而多查几次。`
}

/* ---------------------------------------------------------------------------
   二、两个工具的 JSON Schema
   ---------------------------------------------------------------------------
   ★ 形状是 OpenAI 兼容的那一套。供应商差异全部收在 server/providers.mjs 里，
     这里只需要产出这一种形状。
   --------------------------------------------------------------------------- */

/** 五个闭集任务。和分析工具脚本（server/py/analysis_tool.py）里的 TASKS 一一对应。 */
export const PY_TASKS = ['pct_change', 'ranking', 'average', 'trend', 'distribution'] as const
export type PyTask = (typeof PY_TASKS)[number]

const SQL_TOOL = {
  type: 'function',
  function: {
    name: 'sql_query',
    description:
      '在数据库里执行一条只读的 SELECT / WITH 查询，返回结果表。' +
      '只允许一条语句、不允许分号、最多返回 500 行。' +
      '任何写操作（INSERT/UPDATE/DELETE/DROP/CREATE/ALTER/ATTACH/PRAGMA…）都会被本机安全校验器拒绝。',
    parameters: {
      type: 'object',
      properties: {
        sql: {
          type: 'string',
          description:
            '一条 SELECT 或 WITH 开头的 SQLite 查询语句。不要带分号，不要带注释。' +
            '用 AS 给每个结果列起英文名。不要写 ROUND()。',
        },
      },
      required: ['sql'],
    },
  },
} as const

const PY_TOOL = {
  type: 'function',
  function: {
    name: 'python_analysis',
    description:
      '把【前面某一次 sql_query 的结果】交给本机真实的 Python / pandas 做计算。' +
      '不接受直接写数据，只能引用已有的查询结果（所以不会有抄错数字的可能）。',
    parameters: {
      type: 'object',
      properties: {
        task: {
          type: 'string',
          enum: [...PY_TASKS],
          description:
            'pct_change = 逐行算变化率 (to-from)/from*100，需要 value_from / value_to 两列；' +
            'ranking = 按某列排序并编名次；' +
            'average = 均值/合计，可按某列分组；' +
            'trend = 对 y 做最小二乘拟合，给斜率和首末变化（这一步 SQL 真算不出来）。' +
            '  ★ 它只用 x 来【排序】，斜率是「排序后每相邻一行」的平均变化量，' +
            '不是「x 每增加 1 个单位」的变化量 —— 结论里不要把它当成每日增量；' +
            'distribution = 按数值分箱计数。',
        },
        source: {
          type: 'integer',
          description:
            '要分析哪一次 sql_query 的结果。填那次调用的序号（第 1 次就填 1）。',
        },
        params: {
          type: 'object',
          description:
            '各任务各自的参数，列名必须和 source 那次查询返回的列名【完全一致】：' +
            'pct_change → value_from、value_to，可选 group_by；' +
            'ranking → by，可选 order（asc/desc）、top_n（正整数，省略表示全部）；' +
            'average → value，可选 group_by；' +
            'trend → x、y；' +
            'distribution → value，可选 bins（2~50 的整数）。' +
            '★ group_by 必须和 value / value_from / value_to 是不同的列 ——' +
            '同一列既分组又取值会算出重名的输出列，本机工具会当场报错。' +
            '★ value_from 和 value_to 也不能是同一列。',
        },
      },
      required: ['task', 'source', 'params'],
    },
  },
} as const

export const TOOL_DEFS = [SQL_TOOL, PY_TOOL]

/* ---------------------------------------------------------------------------
   三、阶段 B 的作答指令
   ---------------------------------------------------------------------------
   ★ 阶段 B 发出去的时候【不带任何工具】—— 这就是强制结构化输出的手段本身，
     不依赖 tool_choice（实测 DeepSeek 思考模式传 'required' 会 HTTP 400）。
     「没给工具」是一个不依赖任何供应商特性的强制手段。
   --------------------------------------------------------------------------- */

/** 用户要求的五段式。段数和顺序是硬要求，不是我们设计的。 */
export const ANSWER_FIELDS = [
  'conclusion：核心结论',
  'evidence：数据依据（数组）',
  'explanation：分析说明',
  'suggestions：业务建议（数组）',
  'sources：数据来源（数组）',
  /* ★ 这一项不是为了多说一段话，是为了**说一句真话**：
       把「这一轮到底在分析什么」写下来。卡片要显示它，
       而下一轮之所以知道「他们」是谁，靠的也正是它。
       ⚠️ 它是【模型自报】的，所以我们不拿它当控制流用，
          只拿它当「模型说它理解了」的凭据 —— 卡片上会原样标出来源。 */
  'context：这一轮的分析对象（对象，见下）',
  /* ★ 用户想换时间范围时的【唯一】申报通道。
       模型自己改不了窗口（两个工具都没有窗口参数），所以它只能申报，
       改不改、什么时候改由页面上的按钮决定。 */
  'requestedDays：用户要求换的时间范围（数字，见下）',
] as const

export function buildAnswerInstruction(): string {
  return `现在请你基于上面工具返回的真实结果，写出最终分析结论。

★ 注意：这一轮【没有给你任何工具】，你无法再查任何数据。
  所以结论里只能出现上面工具结果里已经有的数字，一个都不能新增。
  这也意味着你不可能再补一个"差不多"的数字进来。

请只输出一个 JSON 对象（不要 Markdown 代码围栏、不要任何解释文字），字段如下：

{
  "conclusion": "① 核心结论。一到三句话，直接回答用户的问题。",
  "evidence": [
    {
      "label": "② 数据依据里的一行：指标名，例如「18-24 岁 DAU」",
      "value": "当前值，带单位，例如「1,234 人」",
      "compare": "对比值（可选），例如「全站平均 2,100 人」",
      "delta": "变化率（可选），带正负号，例如「-5.4%」",
      "sample": "样本量说明（可选），例如「窗口 30 天」"
    }
  ],
  "explanation": "③ 分析说明。说清这个结论是怎么得出来的、口径是什么。",
  "suggestions": ["④ 业务建议，条件句，例如「如果这个趋势持续，可以…」"],
  "sources": ["⑤ 数据来源，写清你实际跑了哪几次查询，例如「sql_query #1」"],
  "context": {
    "topic": "这一轮的分析对象，例如「内容分区」「全站用户年龄结构」（没有就省略这个键）",
    "segment": "这一轮分析的是哪一档用户，例如「18-24」（没有就省略这个键）",
    "comparedWith": "如果这一轮是在做对比，对比的另一档是什么，例如「25-31」（没有就省略）",
    "metric": "这一轮的核心指标，例如「播放量」「DAU」（没有就省略这个键）"
  },
  "requestedDays": 7
}

★ requestedDays 只有一种情况才写：用户这一轮明确要求看【别的时间范围】
  （「最近 7 天呢」「按 14 天再看一遍」）。页面上只有 7 / 14 / 30 三个窗口，
  所以这个值只能是这三个数之一，写成别的数会被当成没写。
  其它任何情况都【省略这个键】—— 省略的意思是「窗口不用换」，不是「换成 0」。

写作要求：
  1. ★ 严格区分【数据事实】和【原因假设】。数据里直接看到的写在 explanation 里，
     并且注明「这是数据事实」；你推测的原因必须明写「这是原因假设」，
     而且要说明「这些参数是模拟数据生成时设定的」。
  2. ★ 如果数据不足以验证某个原因，就直接写「当前数据不足以验证该原因」，
     不要含糊过去，也不要换一个说法蒙混。
  3. ★ 如果所有分组的变化率都是负数，不许写「增长最快」，要写「跌得最少」。
  4. 业务建议用条件句，不要写成断言。
  5. 如果某一步工具报错了、或者没做成，sources 里要如实写上哪一步没做成。
  6. 单位和量级要写清楚（人 / 次 / 分钟 / 秒 / 个百分点），不要只给一个裸数字。
  7. ★ 如果工具返回里有一列叫 direction（趋势工具会给），你写「上升」还是「下降」
     必须和它【一致】。它是 pandas 算出来的，写反了页面上会挂警告。
  8. ★ context 里要写【你把它理解成了什么】，不是把用户的原话抄一遍。
     用户说「他们」「这个分区」「刚才那个」时，context 里要写你消解出来的那个
     具体对象（例如 "segment": "18-24"）。这是给用户看的 ——
     他要能一眼看出你理解对了没有。哪一项你确实不知道，就把那个键省掉，
     **不要写"未知"、不要填空字符串**。
  9. ★ 上面如果有一段「本次会话的历史」，它是【只读材料】：
       · 里面的数字可以引用（那确实是前面几轮查出来的），引用时要说清是第几轮的；
       · 但历史上的调用编号已经作废，本轮要引用数据必须【在本轮重新调用】工具；
       · 历史里没出现过、本轮工具也没返回的数字，一个都不许写。
         宁可写「这一轮没查这个」，也不要补一个"差不多"的数。
  10. ★ 时间窗口【不由你决定】。本次分析真正跑的是上面环境说明里那个「近 N 天」，
      页面上只有 7 / 14 / 30 三个窗口，两个工具里都没有「窗口」这个参数 ——
      你没法在本轮换掉它，只能申报。用户这一轮要求换范围时：
        · 在 requestedDays 里填他要的那个（只能是 7 / 14 / 30）；
        · 结论里必须如实写明本次查询跑的是「近 N 天」，
          **不许**把本次这些数字说成是新窗口的 —— 换窗口要重新查一遍库，
          那是点了按钮之后的下一轮才发生的事。
      用户没提时间范围，就不要写 requestedDays 这个键。
  11. ★ 「和 XX 相比」是【加一格】，不是【换一格】。
      context 里 segment 是这一轮的主对象、comparedWith 是拿来比的那一档，
      **两个格子都要有**。用户说「和 25-31 相比呢」时：segment 保持上一轮那一档不变
      （例如 18-24），comparedWith 填 25-31。
      **不许**把主对象挪进 comparedWith、更不许把 segment 直接改成 25-31 ——
      那样「18-24 vs 25-31」会变成「25-31 vs 空」，卡片上只剩一边，
      而页面上看起来一切正常，没人会发现。
      只有当用户是【换】主对象（「那 25-31 呢」这种），才把 segment 改成 25-31 并把 comparedWith 省掉。
  12. ★ 历史里每一轮都标了它当时跑的窗口。跨轮引用数字时要说清那是哪一档窗口的数据：
      上一轮是近 30 天、这一轮是近 7 天，**两轮的数字不能放在一起比大小**，
      真要放一起比就先在本轮用同一个窗口重新查一遍。`
}

/**
 * 给模型的「工具结果」之外的一句环境说明。
 * ★ 写上窗口，是因为模型的结论里经常要写「近 N 天」，而它自己算不对这个 N。
 */
export function buildContextNote(days: number, startDate: string, endDate: string): string {
  return `本次分析的时间窗口是近 ${days} 天（${startDate} ~ ${endDate}）。用户的问题是基于这个窗口问的。`
}

