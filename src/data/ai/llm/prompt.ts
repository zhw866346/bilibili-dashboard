/* ==========================================================================
   系统提示词 + 两个工具的 JSON Schema
   --------------------------------------------------------------------------
   ★ 提示词为什么必须在前端拼（而不是放在后端）：
     循环跑在前端（见 loop.ts），工具也在前端执行。提示词里要嵌的口径卡片
     是【从 src/ 下的真源码现算的】。放到后端就等于在 .mjs 里再抄一份口径 ——
     两个真相来源，改一处漏一处不会报错。这个坑项目里踩过。

   ★ 这里刻意【不做复杂的事】：
     没有自我反思、没有多轮规划、没有子任务分解。就是
     「给两个工具 → 模型调 → 本地执行 → 结果回填 → 它再决定 → 最后写结论」。
     规则路径的能力边界已经够清楚了，这里要做的增量是【换成真模型 + 数字被核验】，
     不是换一套更花哨的编排。
   ========================================================================== */

