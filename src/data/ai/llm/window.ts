/* ==========================================================================
   时间窗口：模型嘴上说的 vs 本次真正跑的
   --------------------------------------------------------------------------
   ★ 先把这件事的背景说清楚，因为它是这个文件存在的全部理由：

     整条链路里「时间窗口」只有一种一等公民 —— 天数 `days`（7 / 14 / 30），
     由页面上的那三个按钮决定、由前端作为 option 传给 runLlmAnalysis。
     模型【没有权力改它】：两个工具的 JSON Schema 里根本没有窗口参数
     （见 prompt.ts 的 TOOL_DEFS），窗口只能体现在它自己写的 SQL 文本里。

     于是「最近 7 天呢」这一句话有两种截然不同的结局：

       · 模型在作答 JSON 里【申报】了 requestedDays → 前端把按钮拨过去。
         窗口真的换了（下一轮才生效），这是真话，不需要警告。
       · 模型只在结论里【嘴上】说了 7 天 → 卡片上仍然老老实实写着近 30 天，
         而结论通篇在讲 7 天。这就是本文件要抓的那种错：
         **它不报错、不抛异常，只是让用户把结论读错。**

   ★ 判据【取松】，这是有意的：
     模型经常写「近 30 天里的最后 7 天」「前半段 7 天 vs 后半段 7 天」
     这类完全正常的句子。判紧了每一条都会误报，而假告警比不检查更糟 ——
     这个项目已经吃过两次亏（坑点 18、21）：核对器一旦开始乱叫，
     用户就再也不信它，包括它真正成立的那几次。
     所以规则是：**真实窗口只要在正文里出现过一次，就不报警**。

   ★ 这里【不】复用 matcher.ts 的 DAYS_ALIASES，理由有两条：
     ① 那张表是用来匹配【用户的问题】的（里面「这周」「上月」这种口语说法），
        而这里要扫的是【模型自己写的正文】；
     ② 把规则路径 import 进大模型路径，会把两条本该互不干扰的路绑在一起
        —— 两条路各自独立、互不干扰，是这个项目刻意保住的一件事。
        真需要共用时，应该把那张表提到中立的地方，而不是互相 import。
   ========================================================================== */

import { RANGES } from '../demos'
import { CONTEXT_WINDOW_MISMATCH } from './history'

/**
 * 页面上真实存在的窗口天数。
 *
 * ★ 【派生自 RANGES，不许手抄一份】—— 手抄就是第二个真相来源：
 *   哪天 RANGES 改成 7/14/30/60，这里若还是硬编码的 [7,14,30]，
 *   模型申报 60 天会被静默拒绝，而两边都不报错。
 *   本机有一条断言专门钉这件事。
 */
export const ALLOWED_DAYS: readonly number[] = RANGES.map((r) => r.days)

export function isAllowedDays(n: unknown): n is number {
  return typeof n === 'number' && Number.isInteger(n) && ALLOWED_DAYS.includes(n)
}

/* ---------------------------------------------------------------------------
   一、从一段中文里认出它说了哪些时间范围
   --------------------------------------------------------------------------- */

/**
 * 口语说法 → 天数。
 * ★ 「一周」「半个月」这些是模型真会写的（它在 explanation 里爱用口语）。
 *   只放无歧义的：例如「上月」就不放 —— 它既可能指「上一个自然月」，
 *   也可能只是「上个月这段时间」，认成 30 天会凭空造出一个假告警。
 */
const DAY_ALIASES: { days: number; re: RegExp }[] = [
  { days: 7, re: /(?:一周|1\s*周|七天)/ },
  { days: 14, re: /(?:两周|2\s*周|半个月|十四天|二周)/ },
  { days: 30, re: /(?:一个月|1\s*个月|三十天|满一个月)/ },
]

/** 阿拉伯数字 + 天。`近 7 天`、`过去 14 天`、`30天` 都走这一条。 */
const NUM_DAYS = /(\d+)\s*天/g

/**
 * 把正文里出现的所有时间范围说法找出来，去重、从小到大。
 *
 * ★ 「第 7 天」要排除掉：那是【窗口内部的第几天】，不是窗口本身。
 *   不排除的话，「窗口的第 7 天」会被当成「用户想看近 7 天」——
 *   一个凭空冒出来的告警。
 */
export function extractWindowMentions(text: string): number[] {
  const found = new Set<number>()
  const s = text ?? ''

  for (const m of s.matchAll(NUM_DAYS)) {
    const at = m.index ?? 0
    /* 往前找第一个非空白字符，是「第」就说明这是序数，不是窗口。
       ★ 这里的空格【不能省】：「第 7 天」中间那个空格是中文里最常见的写法，
         只看紧邻字符的话，「窗口的第 7 天」会被当成「用户想看近 7 天」——
         一个凭空冒出来的告警，而且它长得完全合理。
         （这一条是后来补的检查逮住的，第一版真就漏了。） */
    let k = at - 1
    while (k >= 0 && /\s/.test(s[k])) k -= 1
    if (k >= 0 && s[k] === '第') continue
    const n = Number(m[1])
    if (Number.isFinite(n) && n > 0) found.add(n)
  }

  for (const { days, re } of DAY_ALIASES) {
    if (re.test(s)) found.add(days)
  }

  return [...found].sort((a, b) => a - b)
}

/* ---------------------------------------------------------------------------
   二、模型口头窗口和真实窗口对不上时的警告
   --------------------------------------------------------------------------- */

/**
 * 正文里通篇没说过本次真实窗口、却在说别的窗口 → 返回那句警告；否则 null。
 *
 * ★ 三种「不报警」的情形，每一种都是刻意的：
 *   1. 正文里【一个字都没提】时间范围   → 没说的不算说错；
 *   2. 正文里【提到过真实窗口】         → 判松的核心，见文件头；
 *   3. 提取出来是空数组                 → 同 1。
 *
 * ★ 为什么返回值直接用 history.ts 里那个常量、不另写一句：
 *   那句话是「不许假装一致」的机器落点，页面上只该有【一处】说法。
 *   两处各写一句，迟早出现「卡片上一句、警告里另一句」，而两边都不报错。
 */
export function windowMismatchNote(text: string, realDays: number): string | null {
  const mentioned = extractWindowMentions(text)
  if (mentioned.length === 0) return null
  if (mentioned.includes(realDays)) return null
  return CONTEXT_WINDOW_MISMATCH
}
